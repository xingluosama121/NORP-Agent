var currentLang = "zh_CN";

function t(key, lang) {
    lang = lang || currentLang;
    var dict = I18N[lang] || I18N["en"];
    return dict[key] !== undefined ? dict[key] : (I18N["en"][key] || key);
}

function setLanguage(lang) {
    currentLang = lang;
    // Update all elements with data-i18n attribute
    var elements = document.querySelectorAll('[data-i18n]');
    for (var i = 0; i < elements.length; i++) {
        var el = elements[i];
        var key = el.getAttribute('data-i18n');
        if (key) {
            var val = t(key, lang);
            // Use innerHTML for translations containing HTML markup (e.g. <b>),
            // textContent otherwise to avoid XSS from user-supplied values.
            if (/<[a-zA-Z][^>]*>/.test(val)) {
                el.innerHTML = val;
            } else {
                el.textContent = val;
            }
        }
    }
    // Update all elements with data-i18n-placeholder attribute
    var placeholders = document.querySelectorAll('[data-i18n-placeholder]');
    for (var j = 0; j < placeholders.length; j++) {
        var pel = placeholders[j];
        var pkey = pel.getAttribute('data-i18n-placeholder');
        if (pkey) {
            pel.placeholder = t(pkey, lang);
        }
    }
    // Update all elements with data-i18n-title attribute
    var titles = document.querySelectorAll('[data-i18n-title]');
    for (var k = 0; k < titles.length; k++) {
        var tel = titles[k];
        var tkey = tel.getAttribute('data-i18n-title');
        if (tkey) {
            tel.title = t(tkey, lang);
        }
    }
    // Update header token display (language may have changed)
    updateHeaderTokensDisplay();
}

function tf(key, lang) {
    // Format version of t() that supports {0}, {1}, etc.
    var args = Array.prototype.slice.call(arguments, 2);
    var text = t(key, lang || currentLang);
    for (var i = 0; i < args.length; i++) {
        text = text.replace('{' + i + '}', args[i]);
    }
    return text;
}

